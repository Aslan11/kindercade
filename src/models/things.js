export function wheel(b, p, r = 0.15, hub = '#ffd23c', w = 0.1) {
  b.cyl('#3a3346', p, r, w, { rot: [PI / 2, 0, 0], bevel: r * 0.3 });
  b.cyl(hub, p, r * 0.52, w + 0.03, { rot: [PI / 2, 0, 0], ao: false });
}
const wheels = (b, xs, z, r, hub) => { for (const x of xs) b.both((s) => wheel(b, [x, r, s * z], r, hub)); };
const pane = (b, p, size) => b.box(GLASS, p, size, { surf: 'shiny', ao: false, ink: true, r: 0.03 });
const lamps = (b, x, y, z) => b.both((s) => b.ball('#fff3b0', [x, y, s * z], [0.03, 0.055, 0.055], { surf: 'glow', ao: false }));

